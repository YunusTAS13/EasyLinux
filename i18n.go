package main

import (
	"sort"
	"strings"
	"sync"
)

var (
	muLang    sync.RWMutex
	curLang   = "tr"
	langNames = []string{"Türkçe", "English", "Español", "日本語", "中文", "한국어", "العربية", "Latina", "Deutsch", "Français", "Italiano"}
	langCodes = []string{"tr", "en", "es", "ja", "zh", "ko", "ar", "la", "de", "fr", "it"}
)

func t(key string) string {
	muLang.RLock()
	code := curLang
	muLang.RUnlock()
	if m, ok := trMap[code]; ok {
		if v, ok := m[key]; ok {
			return v
		}
	}
	if v, ok := trMap["tr"][key]; ok {
		return v
	}
	return key
}

func setLang(code string) {
	muLang.Lock()
	curLang = code
	muLang.Unlock()
}

func langList() []string {
	return append([]string{}, langNames...)
}

func langNameToCode(name string) string {
	for i, n := range langNames {
		if n == name {
			return langCodes[i]
		}
	}
	return "tr"
}

func sortedLanguages() []string {
	out := append([]string{}, langCodes...)
	sort.Strings(out)
	_ = strings.Join(out, " ")
	return out
}

